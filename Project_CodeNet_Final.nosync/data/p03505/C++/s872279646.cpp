typedef long long ll;
typedef unsigned long long ull;
ll gcd(ll a,ll b) { return b==0?a:gcd(b,a%b); }

ll want, a, b;

ll solve() {
	if (a >= want) return 1;
	if (a <= b) return -1;
	ll d = a - b;
	ll left = want - a;
	ll t = (left + d - 1) / d;
	return 1 + 2 * t;
}

void run() {
	scanf("%lld%lld%lld", &want, &a, &b);
	printf("%lld\n", solve());
}

int main() {
	run();
	return 0;
}
