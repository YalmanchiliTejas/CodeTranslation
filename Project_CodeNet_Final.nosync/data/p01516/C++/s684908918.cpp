bool isis_ll(Line l, Line m) {
	return !eq(cross(l.b - l.a, m.b - m.a), 0);
}

// ??´?????¨?????????????????????
bool isis_ls(Line l, Line s) {
	return isis_ll(l, s) &&
		(cross(l.b - l.a, s.a - l.a) * cross(l.b - l.a, s.b - l.a) < eps);
}

// ????????¨?????????????????????
bool isis_ss(Line s, Line t) {
	return ccw(s.a, s.b, t.a) * ccw(s.a, s.b, t.b) <= 0 &&
		ccw(t.a, t.b, s.a) * ccw(t.a, t.b, s.b) <= 0;
}

// ????????´????????????
bool isis_lp(Line l, Point p) {
	return (abs(cross(l.b - p, l.a - p)) < eps);
}

// ?????????????????????
bool isis_sp(Line s, Point p) {
	return (abs(s.a - p) + abs(s.b - p) - abs(s.b - s.a) < eps);
}

// ??????????¶?
Point proj(Line l, Point p) {
	ld t = dot(p - l.a, l.a - l.b) / norm(l.a - l.b);
	return l.a + t * (l.a - l.b);
}

// ??´?????¨??´????????????
Point is_ll(Line s, Line t) {
	Point sv = s.b - s.a, tv = t.b - t.a;
	assert(cross(sv, tv) != 0);
	return s.a + sv * cross(tv, t.a - s.a) / cross(tv, sv);
}

// ??´?????¨???????????¢
ld dist_lp(Line l, Point p) {
	return abs(p - proj(l, p));
}

// ??´?????¨??´???????????¢
ld dist_ll(Line l, Line m) {
	return isis_ll(l, m) ? 0 : dist_lp(l, m.a);
}

// ??´?????¨??????????????¢
ld dist_ls(Line l, Line s) {
	return isis_ls(l, s) ? 0 : min(dist_lp(l, s.a), dist_lp(l, s.b));
}

// ????????¨???????????¢
ld dist_sp(Line s, Point p) {
	Point r = proj(s, p);
	return isis_sp(s, r) ? abs(r - p) : min(abs(s.a - p), abs(s.b - p));
}

// ????????¨??????????????¢
ld dist_ss(Line s, Line t) {
	if (isis_ss(s, t)) return 0;
	return min({ dist_sp(s, t.a), dist_sp(s, t.b), dist_sp(t, s.a), dist_sp(t, s.b) });
}

ld theta = 72.0*pi / 180;
struct star {
	ld x, y, a, r;
	vector<Point> P;
	vector<Line> L;
	star() {}
	star(ld x, ld y, ld a, ld r) :x(x), y(y), a(a), r(r) {
		ld w = (90.0 + a)*pi / 180;
		for (int i = 0; i < 5;i++) {
			ld px = x + r * cos(w + theta*i);
			ld py = y + r * sin(w + theta*i);
			P.push_back(Point(px, py));
		}
		for (int i = 0; i < 5;i++) {
			L.push_back(Line(P[i], P[(i + 2) % 5]));
		}
	}
};

const ld INF = 1e9;

ld getCost(star& s1, star& s2) {
	ld ret = INF;
	for (int i = 0; i < 5;i++) {
		for (int j = 0;j < 5;j++) {
			ret = min(ret, dist_ss(s1.L[i], s2.L[j]));
		}
	}
	return ret;
}
int main() {
	cin.tie(0); ios::sync_with_stdio(false);
	int N, M, L;
	while (cin >> N >> M >> L, N | M | L) {
		M--; L--;
		vector<star> Star(N);
		for (int i = 0; i < N;i++) {
			ld x, y, a, r; cin >> x >> y >> a >> r;
			Star[i] = star(x, y, a, r);
		}
		vector<vector<ld>> dist(N, vector<ld>(N, INF));
		for (int i = 0; i < N;i++) dist[i][i] = 0.0;

		for (int i = 0; i < N;i++) {
			for (int j = i + 1; j < N;j++) {
				ld cost = getCost(Star[i], Star[j]);
				dist[i][j] = cost;
				dist[j][i] = cost;
			}
		}

		for (int i = 0; i < N;i++) {
			for (int j = 0; j < N;j++) {
				for (int k = 0; k < N;k++) {
					dist[j][k] = min(dist[j][k], dist[j][i] + dist[i][k]);
				}
			}
		}
		cout << fixed << setprecision(20) << dist[M][L] << endl;
	}
}