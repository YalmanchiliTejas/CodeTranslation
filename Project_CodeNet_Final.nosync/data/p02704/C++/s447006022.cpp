const int Inf=0x3f3f3f3f;

namespace nf{
	struct Edge{
		int to,cap,rev;
		Edge(int to,int cap,int rev):to(to),cap(cap),rev(rev){}
	};
	vector<Edge> egs[1005];
	int base;
	void init(){
		base=0;
		for(int i=0;i<1005;i++){
			egs[i].clear();
		}
	}
	void newedge(int u,int v,int cap){
		egs[u].emplace_back(v,cap,egs[v].size());
		egs[v].emplace_back(u,0,egs[u].size()-1);
	}
	void newedge(int u,int v,int l,int r){
		newedge(0,v,l);
		newedge(u,1,l);
		newedge(u,v,r-l);
		base+=l;
	}
	int dist[1005],iter[1005];
	void bfs(){
		memset(dist,-1,sizeof(dist));
		dist[0]=0;
		queue<int> q;
		q.push(0);
		while(q.size()){
			int x=q.front();
			q.pop();
			for(int i=0;i<egs[x].size();i++){
				Edge &e=egs[x][i];
				if(e.cap&&!~dist[e.to]){
					dist[e.to]=dist[x]+1;
					q.push(e.to);
				}
			}
		}
	}
	int dfs(int now,int cap){
		if(now==1){
			return cap;
		}
		for(int &i=iter[now];i<egs[now].size();i++){
			Edge &e=egs[now][i];
			if(e.cap&&dist[e.to]==dist[now]+1){
				int fl=dfs(e.to,min(cap,e.cap));
				if(fl){
					e.cap-=fl;
					egs[e.to][e.rev].cap+=fl;
					return fl;
				}
			}
		}
		return 0;
	}
	int getflow(){
		int fl=0;
		while(1){
			bfs();
			if(!~dist[1]){
				break;
			}
			memset(iter,0,sizeof(iter));
			int f;
			while((f=dfs(0,Inf))){
				fl+=f;
			}
		}
		return fl;
	}
}

