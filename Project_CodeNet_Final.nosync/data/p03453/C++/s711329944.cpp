  REP(i,n){
    for(P e:edge[i]){
      int a = i, b = e.fs, co = e.sc;
      if(dist1[a]*2 < d && dist1[b]*2 > d && dist1[a]+co == dist1[b]){
      //  cout << "*" SP a SP  b << endl;
        add(ans,-modpow(mul(dp_s[a],dp_t[b]),2));
      }
    }
  }

