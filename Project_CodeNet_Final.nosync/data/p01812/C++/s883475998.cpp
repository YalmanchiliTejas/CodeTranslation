#include <iostream>
#include <vector>
#include <queue>
using namespace std;

int n, m, k;
int d[16];
vector<int> et[100];
int blackId[100];

void input() {
	int v;
	int i, j;
	cin >> n >> m >> k;
	for (i = 0; i < n; i++) { blackId[i] = -1; }
	for (i = 0; i < m; i++) {
		cin >> d[i]; d[i]--;
		blackId[d[i]] = i;
	}
	for (i = 0; i < n; i++) {
		for (j = 0; j < k; j++) {
			cin >> v; v--;
			et[i].push_back(v);
		}
	}
}

int dp[1 << 16];

int main() {
	input();
	
	for (int i = 0; i < (1 << m); i++) dp[i] = 11451419;
	queue<int> que;
	
	que.push((1 << m) - 1);
	dp[(1 << m) - 1] = 0;
	while (!que.empty()) {
		int state = que.front(); que.pop();
		
		for (int i = 0; i < k; i++) {
			int nState = 0;
			for (int j = 0; j < m; j++) {
				if ((state >> j) % 2 == 0) continue;
				int id = blackId[et[d[j]][i]];
				if (id == -1) continue;
				nState |= (1 << id);
			}
			if (dp[nState] > dp[state] + 1) {
				dp[nState] = dp[state] + 1;
				que.push(nState);
			}
		}
	}
	
	cout << dp[0] << endl;
	return 0;
}