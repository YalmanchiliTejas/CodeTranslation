#include <bits/stdc++.h>
#define int long long int
#define F first
#define S second

using namespace std ;

const int N = 4000 ;
int n , a[N] , dp[N][N] , ps[N];

void maker(int nn){
	for(int i = 1 ; i <= nn ; i++){
		ps[i] = ps[i - 1] + a[i] ;
	}
}

int pr(int l , int r){
	return (ps[r] - ps[l - 1]) ;
}

int32_t main(){
	cin >> n ;
	for(int i = 1 ; i <= n ; i++)cin >> a[i] , dp[i][i] = a[i];
	maker(n) ;
	for(int i = 1 ; i < n ; i++){
		for(int l = 1 ; l + i <= n ; l++){
			dp[l][l + i] = max(pr(l , l + i - 1) - dp[l][i + l - 1] + a[i + l] , pr(l + 1, l + i) - dp[l + 1][i + l] + a[l] );
		}
	}
	cout << 2 * dp[1][n] - pr(1 , n) ;
	return 0 ; 
}
