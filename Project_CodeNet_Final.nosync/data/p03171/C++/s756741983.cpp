#include<bits/stdc++.h>
using namespace std;
#include <ext/pb_ds/assoc_container.hpp>
using namespace __gnu_pbds;
#define lli long long int
lli a[3001];
lli INF=1e18;
lli dp[3001][3001][2];
lli f(lli i, lli j, lli c){
    //cout<<i<<" "<<j<<endl;
    if(i==j){
        if(c==1)return (-a[i]);
        else return a[i];
    }
    if(dp[i][j][c]!=INF)return dp[i][j][c];
    if(c==0)return dp[i][j][c]=(max(a[i]+f(i+1,j,1),a[j]+f(i,j-1,1)));
    else return dp[i][j][c]=(min(-a[i]+f(i+1,j,0),-a[j]+f(i,j-1,0))); 
}

int main()
{
 	ios::sync_with_stdio(0);
    cin.tie(0);
        lli n;
        cin>>n;
        for(lli i=0;i<=n;i++)for(lli j=0;j<=n;j++)dp[i][j][0]=INF,dp[i][j][1]=INF;
        for(lli i=0;i<n;i++)cin>>a[i];
        cout<<f(0,n-1,0);
        

  

 }