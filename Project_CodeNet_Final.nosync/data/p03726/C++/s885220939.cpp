int n, a, b, s;
vector<int> g[100100];
int u[100100];
bool f = false;
int c[100100];

void dfs(int v, int pr = -1)
{
	if (g[v].size() == 1)
	{
		c[v] = 2;
		return;
	}
	int co[2];
	co[0] = 0;
	co[1] = 0;
	for (int i = 0; i < g[v].size(); i++)
	{
		if (g[v][i] == pr)
			continue;
		dfs(g[v][i], v);
		if (c[g[v][i]] == 1)
		{
			co[0]++;
		}
		if (c[g[v][i]] == 2)
		{
			co[1]++;
		}
	}
	if (pr == -1)
	{
		if (co[1] == 0)
		{
			f = true;
		}
	}
	if (co[1] > 1)
	{
		f = true;
	}
	if (co[1])
	{
		c[v] = 1;
	}
	else
	{
		c[v] = 2;
	}
	return;
}

