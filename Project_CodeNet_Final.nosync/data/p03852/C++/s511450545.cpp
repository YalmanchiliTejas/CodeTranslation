#include <bits/stdc++.h>
using namespace std;
 
int main() {
  char c ;
  
  char a = 'a';
  char e = 'e';
  char i = 'i';
  char o = 'o';
  char u = 'u';
  
  cin >> c;

  if((c == a) || (c == e) || (c == i) || (c == o) || (c == u)){
  cout << "vowel" << endl;
  }

  else{
  cout << "consonant" << endl;
  }
}