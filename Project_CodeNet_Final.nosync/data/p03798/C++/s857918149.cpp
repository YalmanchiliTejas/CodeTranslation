#include <bits/stdc++.h>
using namespace std;
int main(){
	string s,c,beg[4]={"SS","SW","WS","WW"};
	int i,j,n;
	cin>>n;
	cin>>s;
	for(j=0;j<4;j++)
	{
		c=beg[j];
		for(i=1;i<n-1;i++)
		{
			if(c[i]=='S')
			{
				if(s[i]=='o')
					c+=c[i-1];
				else
				{
					if(c[i-1]=='S')
						c+="W";
					else
						c+="S";
				}
			}
			else
			{
				if(s[i]=='x')
					c+=c[i-1];
				else
				{
					if(c[i-1]=='S')
						c+="W";
					else
						c+="S";
				}
			}
		}
		if(c[0]=='S')
		{
			if(s[0]=='o')
			{
				if(c[1]!=c[n-1])
					continue;
			}
			else
				if(c[1]==c[n-1])
					continue;
		} 
		else
		{
			if(s[0]=='x')
			{
				if(c[1]!=c[n-1])
					continue;
			}
			else
				if(c[1]==c[n-1])
					continue;
		}
		if(c[n-1]=='S')
		{
			if(s[n-1]=='o')
			{
				if(c[0]!=c[n-2])
					continue;
			}
			else
				if(c[0]==c[n-2])
					continue;
		} 
		else
		{
			if(s[n-1]=='x')
			{
				if(c[0]!=c[n-2])
					continue;
			}
			else
				if(c[0]==c[n-2])
					continue;
		}
		cout<<c<<endl;
		return 0;
	}
	cout<<"-1"<<endl;
	return 0;
}