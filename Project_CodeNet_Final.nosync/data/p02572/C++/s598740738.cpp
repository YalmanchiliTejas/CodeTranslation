using ll = long long;
using ld = long double;
using pii = pair<int, int>;
using pli = pair<ll, int>;

const int N = 300 * 1000 + 5;
const ll mod = 1000000007;
const ll INF = 1000000000 * 1ll * 1000000000 + 500000;
const ld pi = acosl(-1.0);

ll a[N], s[N];
int n;

void input() {
    cin >> n;
    for (int i = 0; i < n; i++) {
        cin >> a[i];
    }
    s[n] = 0;
    for (int i = n - 1; i >= 0; i--) {
        s[i] = (s[i + 1] + a[i]) % mod;
    }
}

void solve(int testId) {
    ll ans = 0;
    for (int i = 0; i < n; i++) {
        ans = (ans + a[i] * 1ll * s[i + 1]) % mod;
    }
    cout << ans << endl;
}

int main() {
    // freopen("test", "r", stdin);
    int testcases = 1;
    // scanf("%d", &testcases);
    for(int testId = 1; testId <= testcases; testId++) {
        input();
        solve(testId);
    }
    return 0;
}
