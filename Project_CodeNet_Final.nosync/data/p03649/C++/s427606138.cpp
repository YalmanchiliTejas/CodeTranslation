int main()
{
	long long n, m;

	std::cin >> n;

	std::vector<long long> v(n);

	for (long long i = 0; i < n; i++) {
		std::cin >> v[i];
	}

	long long ans = 0, count = 0;

	while (true) {
		std::sort(v.begin(), v.end(), std::greater<long long>());
		if (v[0] < n) {
			break;
		}
		long long a = v[0] / n;
		v[0] %= n;
		ans += a;
		for (long long i = 1; i < n; i++) {
			v[i] += a;
		}
	}

	std::cout << ans << std::endl;

	return 0;
}