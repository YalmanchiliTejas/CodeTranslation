std::string getFizzBuzzString(int n)
{
    std::string fizzBuzzString;
    
    if(n % 15 == 0)
    {
        fizzBuzzString = "FizzBuzz";
    }
    else if(n % 5 == 0)
    {
        fizzBuzzString = "Buzz";
    }
    else if(n % 3 == 0)
    {
        fizzBuzzString = "Fizz";
    }
    else
    {
        fizzBuzzString = std::to_string(n);
    }
    
    return fizzBuzzString;
}

