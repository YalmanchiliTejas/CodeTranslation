long long Val( long long n, long long x )
{
int i;
long long a;
long long b;

	if( x >= H[ n ] ) return P[ n ];
	if( n == 0 ) return 0;

	a = H[ n - 1 ];
	b = P[ n - 1 ];
	if( x == a + 2 ) return b + 1;
	else if( x == a + 1 ) return b;
	else if( x <= a ) return Val( n - 1, x - 1 );
	else return b + 1 + Val( n - 1, x - a - 2 );

}


