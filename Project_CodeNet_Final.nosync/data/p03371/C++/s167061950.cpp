int main(void)
{
    cin.tie(0);
    ios::sync_with_stdio(false);
    int A,B,C,X,Y; cin>>A>>B>>C>>X>>Y;
    C*=2;
    chmin(C,A+B);
    ll ans=(ll)1e15;
    FOR(i,min(X,Y),max(X,Y)){
        ll cand=0;
        cand+=(ll)i*C;
        int x=X-i,y=Y-i;
        chmax(x,0); chmax(y,0);
        cand+=(ll)x*A;
        cand+=(ll)y*B;
        chmin(ans,cand);
    }
    cout<<ans<<"\n";
    return 0;
}
