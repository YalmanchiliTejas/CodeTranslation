using namespace std;

int main() {
	int a, b, c, x, y;
	cin >> a >> b >> c >> x >> y;
	int result = 0;
	if (a + b > 2 * c) {
		result += min(x, y) * 2 * c;
		if (x > y) {
			x -= y;
			if (a > 2 * c) {
				result += x * 2 * c;
			}
			else {
				result += x * a;
			}
		}
		else if (x < y) {
			y -= x;
			if (b > 2 * c) {
				result += y * 2 * c;
			}
			else {
				result += y * b;
			}
		}
	}
	else {
		result += a * x + b * y;
	}
	cout << result << endl;
}

